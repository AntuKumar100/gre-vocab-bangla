export function translate(lang: Lang, text: string, vars?: Record<string, string | number>) {
  let out = lang === "bn" ? (BN[text] ?? text) : text;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(lang === "bn" ? toBnDigits(String(v)) : String(v));
  return out;
}

const BN_DIGITS = "০১২৩৪৫৬৭৮৯";
export function toBnDigits(s: string) {
  return s.replace(/[0-9]/g, (d) => BN_DIGITS.charAt(Number(d)));
}

/** t("Review {n}", { n: 3 }) in the learner's chosen interface language. */
export function useT() {
  const lang = useProgress().settings.lang;
  return (text: string, vars?: Record<string, string | number>) => translate(lang, text, vars);
}
